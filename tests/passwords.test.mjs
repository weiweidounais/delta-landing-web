import assert from "node:assert/strict";
import {normalizeKkrbSource,normalizeDeltaSource,mergeSources,currentSnapshot,sourceFailure,nextUpdate} from "../lib/password-model.ts";
const now=new Date("2026-10-09T11:15:00Z");
const kkr={code:1,data:{db:{password:"2129",updated:"20261009000001"},cgxg:{password:"2861",updated:"20261009000001"},bks:{password:"6241",updated:"20261009000001"},htjd:{password:"0159",updated:"20261009000001"},cxjy:{password:"6463",updated:"20261009000001"},az3:{password:"8967",updated:"20261009000001"},az3r6:{password:"266",updated:"20260822042438"}}};
const delta={entries:[{id:"zero-dam",code:"2129",location:"地下管道"},{id:"space-city",code:"0159",location:"组装室2楼"},{id:"az3",code:null}],fetchedAt:"2026-10-09T11:14:00Z",sourceDate:null,region:null,stale:false,error:null};
const a=normalizeKkrbSource(kkr,now),b=normalizeDeltaSource(delta,now);
let merged=mergeSources([a,b],now);
assert.equal(merged.entries.length,6);
assert.equal(merged.entries[0].doors[0].candidates.length,1);
assert.deepEqual(merged.entries[0].doors[0].candidates[0].sources,["kkrb","deltaforce"]);
assert.deepEqual(merged.entries[0].doors[0].candidates[0].locations,["地下管道"]);
assert.equal(merged.entries[3].code,"0159");
assert.equal(merged.entries[5].code,"8967");
assert.equal(merged.entries[5].doors[1].candidates[0].code,"266");
assert.equal(merged.entries[5].doors[1].candidates[0].needsVerification,true);
assert.equal(a.sourceDate,null);
assert.equal(merged.sourceDate,null);
assert.equal(a.entries[6].updatedAt,"2026-08-22 04:24:38");
assert.throws(()=>normalizeKkrbSource({code:-101,msg:"系统繁忙"},now));
assert.throws(()=>normalizeDeltaSource({...delta,stale:true},now));
assert.throws(()=>normalizeDeltaSource({...delta,sourceDate:"2026-10-08"},now));
assert.throws(()=>normalizeDeltaSource({...delta,fetchedAt:"2026-10-08T11:00:00Z"},now));
const different=normalizeDeltaSource({...delta,entries:[{id:"zero-dam",code:"0007",location:"地下管道"}]},now);
merged=mergeSources([a,different],now);
assert.equal(merged.entries[0].doors[0].status,"conflict");
assert.equal(merged.entries[0].doors[0].candidates.length,2);
assert.equal(merged.entries[0].code,null);
assert.equal(merged.entries[0].doors[0].candidates[1].code,"0007");
const sameAcrossMaps=normalizeKkrbSource({code:1,data:{db:{password:"0123"},az3:{password:"0123"},az3r6:{password:"123"}}},now);
merged=mergeSources([sameAcrossMaps],now);
assert.equal(merged.entries[0].code,"0123");assert.equal(merged.entries[5].code,"0123");
assert.equal(merged.entries[5].doors[1].candidates[0].code,"123");
merged=mergeSources([sourceFailure("kkrb","暂不可用"),b],now);
assert.equal(merged.entries[0].code,"2129");assert.equal(merged.status,"ready");
merged=mergeSources([a,sourceFailure("deltaforce","暂不可用")],now);
assert.equal(merged.entries[5].code,"8967");
assert.equal(currentSnapshot(merged,new Date("2026-10-09T16:00:00Z")).entries.every(e=>e.doors.every(d=>!d.candidates.length)),true);
assert.equal(currentSnapshot({...merged,schemaVersion:1},now).fetchedAt,null);
assert.equal(currentSnapshot(merged,new Date("2026-10-09T11:16:00Z")).fetchedAt,merged.fetchedAt);
assert.equal(nextUpdate(new Date("2026-10-09T17:59:59Z")),"2026-10-09T18:00:00.000Z");
assert.equal(nextUpdate(new Date("2026-10-09T18:00:00Z")),"2026-10-10T18:00:00.000Z");
console.log("Password source tests passed: deduplication, map/door boundaries, conflicts, leading zeros, source isolation, dates and midnight rollover.");
